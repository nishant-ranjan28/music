/* OG share card. SVG is generated here; convert to og.png before launch
   (see README) because X/WhatsApp will not render an SVG link preview. */
function ogSvg(theme) {
  const bg = theme.tokens["--bg"];
  const accent = theme.tokens["--accent"];
  const dim = theme.tokens["--ink-dim"];
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
  <defs>
    <radialGradient id="g" cx="50%" cy="0%" r="90%">
      <stop offset="0%" stop-color="${accent}" stop-opacity="0.28"/>
      <stop offset="100%" stop-color="${bg}" stop-opacity="0"/>
    </radialGradient>
    <filter id="n"><feTurbulence type="fractalNoise" baseFrequency="0.85" numOctaves="3"/></filter>
  </defs>
  <rect width="1200" height="630" fill="${bg}"/>
  <rect width="1200" height="630" fill="url(#g)"/>
  <text x="600" y="290" text-anchor="middle" font-family="${theme.fonts.display}, Georgia, serif"
        font-size="96" fill="${accent}">${esc(theme.sign)}</text>
  <text x="600" y="356" text-anchor="middle" font-family="${theme.fonts.body}, sans-serif"
        font-size="27" letter-spacing="7" fill="${dim}">${esc(
          theme.kicker.toUpperCase()
        )}</text>
  <text x="600" y="452" text-anchor="middle" font-family="${theme.fonts.body}, sans-serif"
        font-size="34" fill="#ffffff" opacity="0.9">${esc(theme.tagline)}</text>
  <text x="600" y="566" text-anchor="middle" font-family="${theme.fonts.body}, sans-serif"
        font-size="24" letter-spacing="10" fill="${accent}" opacity="0.8">${esc(theme.name.toUpperCase())}</text>
  <rect width="1200" height="630" filter="url(#n)" opacity="0.06"/>
</svg>
`;
}

/* Favicon: accent-filled tile with the station glyph, so ten open tabs stay
   tellable apart at 16px. The glyph is rendered as text — every one used is
   in the system emoji/symbol fallback chain on macOS, Windows and Android. */
function faviconSvg({ bg, fg, glyph, size = 0.62 }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <rect width="64" height="64" rx="14" fill="${bg}"/>
  <text x="32" y="32" text-anchor="middle" dominant-baseline="central"
        font-size="${Math.round(64 * size)}" fill="${fg}"
        font-family="Helvetica Neue, Segoe UI Symbol, Noto Sans Symbols 2, sans-serif"
      >${esc(glyph)}&#xFE0E;</text>
</svg>
`;
}

