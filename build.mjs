/* ---------- run ------------------------------------------------------- */

let written = 0;
for (const theme of themes) {
  const dir = join(SITES, theme.slug);
  const playlist = playlistFile(theme); // read old ids BEFORE wiping
  const idCount = (playlist.match(/"yt": "/g) || []).length;

  // Overwrite the generated files in place rather than wiping the directory —
  // og.png and any other hand-made asset alongside them must survive a rebuild.
  mkdirSync(dir, { recursive: true });

  writeFileSync(join(dir, "index.html"), indexHtml(theme));
  writeFileSync(join(dir, "theme.css"), themeCss(theme));
  writeFileSync(join(dir, "playlist.js"), playlist);
  writeFileSync(join(dir, "og.svg"), ogSvg(theme));
  writeFileSync(
    join(dir, "favicon.svg"),
    faviconSvg({
      bg: theme.tokens["--accent"],
      fg: theme.tokens["--on-accent"] || theme.tokens["--bg"],
      glyph: theme.glyph
    })
  );

  written++;
  console.log(
    `  ${theme.slug.padEnd(16)} ${String(theme.tracks.length).padStart(2)} tracks` +
      `  ${idCount}/${theme.tracks.length} ids resolved`
  );
}

/* Every station in one file, so the switcher can change stations in place
   instead of navigating — a page load would tear down the audio. */
writeFileSync(
  join(ROOT, "shared", "stations.js"),
  "window.STATIONS = " +
    JSON.stringify(
      themes.map((t) => ({
        slug: t.slug,
        kind: t.kind,
        name: t.name,
        signHtml: esc(t.sign).replace(/ {2}/g, "&nbsp;&nbsp;"),
        kicker: t.kicker,
        tagline: t.tagline,
        glyph: t.glyph,
        accent: t.tokens["--accent"],
        bg: t.tokens["--bg"],
        fontsHref: t.fonts.href,
        scene: t.scene.trim(),
        site: siteConfig(t),
        tracks: trackList(t)
      })),
      null,
      1
    ) +
    ";\n"
);

writeFileSync(join(ROOT, "index.html"), hubHtml());
writeFileSync(
  join(ROOT, "favicon.svg"),
  faviconSvg({ bg: "#0b0b0d", fg: "#f2efe9", glyph: "◉", size: 0.5 })
);
console.log(`\nbuilt ${written} stations + hub → open index.html`);
