/* ============================================================
   build.mjs — generates sites/<slug>/ for every theme, plus the
   hub page at the repo root.

   Run:  node build.mjs
   ============================================================ */

import { mkdirSync, writeFileSync, existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { themes, GRAIN } from "./themes/themes.mjs";

const ROOT = dirname(fileURLToPath(import.meta.url));
const SITES = join(ROOT, "sites");

/** Public origin, used only for absolute og:/twitter: URLs. Set this to the
 *  real domain before launch — link previews need absolute URLs. */
const ORIGIN = process.env.SITE_ORIGIN || "https://music-eight-smoky.vercel.app";

/* ---------- helpers ------------------------------------------------- */

const esc = (s) =>
  String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

/** Merge previously-resolved YouTube ids back in so `node build.mjs`
 *  never wipes work done by scripts/fill-ids.mjs. */
function existingIds(slug) {
  const file = join(SITES, slug, "playlist.js");
  if (!existsSync(file)) return {};
  const map = {};
  const src = readFileSync(file, "utf8");
  const re = /"title":\s*"((?:[^"\\]|\\.)*)"[\s\S]*?"yt":\s*(?:"([\w-]{11})"|null)/g;
  let m;
  while ((m = re.exec(src))) {
    if (m[2]) map[JSON.parse('"' + m[1] + '"')] = m[2];
  }
  return map;
}

/* ---------- per-site files ------------------------------------------ */

function trackList(theme) {
  const known = existingIds(theme.slug);
  return theme.tracks.map(([title, artist, year]) => ({
    title,
    artist,
    year: year ?? null,
    q: `${title} ${artist}`,
    yt: known[title] ?? null
  }));
}

function siteConfig(theme) {
  return {
    name: theme.name,
    tagline: theme.tagline,
    glyph: theme.glyph,
    shuffle: true,
    searchFallback: true,
    ytPlaylist: theme.ytPlaylist || null,
    maxSeconds: theme.maxSeconds || null
  };
}

function playlistFile(theme) {
  return `/* generated by build.mjs — safe to hand-edit the "yt" ids,
   they are preserved on the next build. */
window.PLAYLIST = ${JSON.stringify(trackList(theme), null, 2)};

window.SITE = ${JSON.stringify(siteConfig(theme), null, 2)};
`;
}

function themeCss(theme) {
  const vars = Object.entries(theme.tokens)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join("\n");

  return `/* generated by build.mjs — edit themes/themes.mjs instead */
:root {
${vars}
  --font-display: "${theme.fonts.display}", Georgia, serif;
  --font-body: "${theme.fonts.body}", system-ui, -apple-system, sans-serif;
  --grain-url: ${GRAIN};
}
${(theme.css || "").replace(/^\n/, "")}
`;
}

